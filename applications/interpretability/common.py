def set_seed(seed: int = 42) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def load_labeled_samples(data_path: Path | str = SAMPLE_DATA_PATH) -> Tuple[List[str], List[str]]:
    """Load medical questions that carry one of the eight department labels.

    Preference order:
    1. ``sample_medical_qa.jsonl`` generated by ``generate_sample_data.py``
       (the generator stores a ``department`` metadata field).
    2. Fall back to importing the generator's ``MEDICAL_QA_TEMPLATES``.
    """
    data_path = Path(data_path)
    if data_path.exists():
        texts: List[str] = []
        labels: List[str] = []
        with data_path.open(encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                item = json.loads(line)
                department = item.get("department")
                if department not in DEPARTMENTS:
                    continue
                question = next(
                    (turn["content"] for turn in item.get("conversations", [])
                     if turn.get("role") == "user"),
                    None,
                )
                if question:
                    texts.append(question)
                    labels.append(department)
        if texts:
            return texts, labels

    # Fallback: read the templates directly, so the demo works without
    # running the data generator first.
    spec = importlib.util.spec_from_file_location("generate_sample_data", GENERATOR_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load sample data or generator: {data_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    texts, labels = [], []
    for department, items in module.MEDICAL_QA_TEMPLATES.items():
        if department not in DEPARTMENTS:
            continue
        for item in items:
            texts.append(item["q"])
            labels.append(department)
    return texts, labels


def segment_words(text: str, remove_stopwords: bool = True) -> List[str]:
    """Segment Chinese text with jieba and drop punctuation.

    ``remove_stopwords=False`` keeps function words so LIME/SHAP have enough
    features to perturb; display code filters them out afterwards.
    """
    import jieba

    words: List[str] = []
    for token in jieba.lcut(text):
        token = token.strip()
        if not token:
            continue
        # Keep tokens that contain at least one Chinese character or letter/digit.
        if not any(ch.isalnum() or "一" <= ch <= "鿿" for ch in token):
            continue
        if remove_stopwords and token in STOPWORDS:
            continue
        words.append(token)
    return words


class MiniMindEmbedder:
    """Frozen MiniMind model returning mean-pooled final hidden states."""

    def __init__(
        self,
        weight_path: Path | str = DEFAULT_WEIGHT_PATH,
        hidden_size: int = 512,
        num_hidden_layers: int = 8,
        device: str = "cpu",
        max_length: int = 128,
        batch_size: int = 64,
    ) -> None:
        weight_path = Path(weight_path)
        if not weight_path.exists():
            raise FileNotFoundError(
                f"Model weight not found: {weight_path}\n"
                "Download it with:\n"
                "  curl -L -o out/full_sft_512.pth "
                "https://www.modelscope.cn/models/gongjy/MiniMind2-PyTorch/resolve/master/full_sft_512.pth"
            )

        self.device = torch.device(device)
        self.tokenizer = AutoTokenizer.from_pretrained(str(MODEL_DIR))
        config = MiniMindConfig(hidden_size=hidden_size, num_hidden_layers=num_hidden_layers)
        self.model = MiniMindForCausalLM(config)
        state_dict = torch.load(weight_path, map_location="cpu")
        self.model.load_state_dict(state_dict, strict=True)
        self.model.eval().to(self.device)

        self.hidden_size = hidden_size
        self.max_length = max_length
        self.batch_size = batch_size

    @property
    def num_parameters(self) -> int:
        return sum(parameter.numel() for parameter in self.model.parameters())

    @torch.no_grad()
    def embed(self, texts: Sequence[str]) -> np.ndarray:
        """Return an ``(n_texts, hidden_size)`` array of mean-pooled features."""
        if len(texts) == 0:
            return np.zeros((0, self.hidden_size), dtype=np.float32)

        cleaned = [text if text and text.strip() else "。" for text in texts]
        chunks: List[np.ndarray] = []
        for start in range(0, len(cleaned), self.batch_size):
            batch = cleaned[start:start + self.batch_size]
            encoded = self.tokenizer(
                batch,
                return_tensors="pt",
                padding=True,
                truncation=True,
                max_length=self.max_length,
            )
            input_ids = encoded["input_ids"].to(self.device)
            attention_mask = encoded["attention_mask"].to(self.device)
            hidden, _, _ = self.model.model(
                input_ids=input_ids,
                attention_mask=attention_mask,
            )
            mask = attention_mask.unsqueeze(-1).to(hidden.dtype)
            pooled = (hidden * mask).sum(dim=1) / mask.sum(dim=1).clamp(min=1)
            chunks.append(pooled.float().cpu().numpy())

        return np.concatenate(chunks, axis=0)


def fit_logistic(
    features: np.ndarray,
    labels: Sequence[str],
    C: float = 1.0,
    class_weight: str | None = "balanced",
    seed: int = 42,
):
    """Fit a standardized logistic-regression probe on frozen features."""
    from sklearn.linear_model import LogisticRegression
    from sklearn.preprocessing import StandardScaler

    scaler = StandardScaler().fit(features)
    classifier = LogisticRegression(
        max_iter=5000,
        C=C,
        class_weight=class_weight,
        random_state=seed,
    )
    classifier.fit(scaler.transform(features), labels)
    return scaler, classifier


def predict_proba(scaler, classifier, features: np.ndarray) -> np.ndarray:
    return classifier.predict_proba(scaler.transform(features))


def save_json(path: Path | str, payload) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
