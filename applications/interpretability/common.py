"""Shared utilities for the MiniMind interpretability experiments.

The idea is deliberately simple and reproducible:

1. Feed a medical question into the frozen 26M MiniMind SFT checkpoint.
2. Take the mean-pooled last-layer hidden state as a sentence representation.
3. Fit a linear probe (logistic regression) for department classification.
4. Explain the probe's predictions with token occlusion, LIME and KernelSHAP.

The probe is not the generative language head; it is a well-defined downstream
prediction task built on MiniMind representations.  This keeps the explanation
target stable while still analysing what the model's hidden states encode.
"""
